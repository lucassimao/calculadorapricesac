// Copies the shared loan engine into an in-root folder that Next/Turbopack can bundle.
// Turbopack cannot resolve imports outside the project root, so the build/dev steps
// consume this generated copy. Source of truth stays in shared/loan-engine/.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, '..', '..', 'shared', 'loan-engine');
const outDir = join(here, '..', 'loan-engine-shim');
const header =
  '// AUTO-GENERATED from shared/loan-engine/ — do not edit.\n' +
  '// Regenerated by scripts/sync-loan-engine.mjs (runs on prebuild/predev).\n\n';

mkdirSync(outDir, { recursive: true });
for (const file of ['calculations.ts', 'loan.ts']) {
  const content = readFileSync(join(srcDir, file), 'utf8');
  writeFileSync(join(outDir, file), header + content);
}
console.log('[sync-loan-engine] copied calculations.ts, loan.ts -> loan-engine-shim/');

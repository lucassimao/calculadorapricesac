// Copies the loan engine into an in-root folder that Next/Turbopack can bundle.
//
// The engine's single source of truth lives in the mobile app
// (mobile/src/lib/calculations.ts + mobile/src/types/loan.ts) — that's where it
// originated and where its 98-test vitest suite runs. The mobile app bundles it
// natively (no config changes, EAS-safe).
//
// Turbopack cannot resolve imports outside the marketing project root, so this
// script copies the two engine files into ./loan-engine-shim (gitignored) on
// prebuild/predev, rewriting the engine's relative `../types/loan` import to the
// sibling `./loan`. The @loan-engine/* aliases point Next at this generated copy;
// tsc and vitest instead alias directly at the mobile source, so the copy cannot
// silently drift (a mismatch would surface as a type or test failure).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mobileSrc = join(here, '..', '..', 'mobile', 'src');
const outDir = join(here, '..', 'loan-engine-shim');
const header =
  '// AUTO-GENERATED from mobile/src (loan engine) — do not edit.\n' +
  '// Regenerated by scripts/sync-loan-engine.mjs (runs on prebuild/predev).\n\n';

mkdirSync(outDir, { recursive: true });

// types: copied verbatim
const loan = readFileSync(join(mobileSrc, 'types', 'loan.ts'), 'utf8');
writeFileSync(join(outDir, 'loan.ts'), header + loan);

// engine: rewrite its `from '../types/loan'` import to the sibling `./loan`
const calculations = readFileSync(join(mobileSrc, 'lib', 'calculations.ts'), 'utf8').replace(
  /from '\.\.\/types\/loan'/,
  "from './loan'",
);
writeFileSync(join(outDir, 'calculations.ts'), header + calculations);

console.log('[sync-loan-engine] copied mobile/src loan engine -> loan-engine-shim/');
